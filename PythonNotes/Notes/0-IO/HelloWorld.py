# Print Syntax
print("Hello", "World!") # Commas automatically add space between arguments
print("Hello" + "World!") # Plus signs concatenate arguments directly.
print(2 + 2)              # Numbers are added, not concatenated here.
print(2, 2)               # Numbers are concatenated here.
print("2 + 2", end="=")   # end="" changes the termination character. Defaults to end="\n"
